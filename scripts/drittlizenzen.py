#!/usr/bin/env python3
"""Write THIRD-PARTY-NOTICES.md: every third-party component with its licence.

Sources:
1. the Python dependencies named in ``requirements.txt`` and ``pyproject.toml``
   plus everything pip installs for them (the transitive closure), read from the
   installed package metadata of the environment this script runs in — licence
   expression, version and the licence files that ship with each package;
2. the front-end library bundled inside the plotly package (served by the app
   as ``/static/plotly.min.js``);
3. the pieces of the Docker image that are not Python packages (base image,
   Tailscale).

Run it in a throwaway environment that has the requirements installed::

    python3 -m venv /tmp/notices-venv
    /tmp/notices-venv/bin/pip install -r requirements.txt
    /tmp/notices-venv/bin/python scripts/drittlizenzen.py > THIRD-PARTY-NOTICES.md

``tests/test_third_party_notices.py`` fails when a dependency listed in
``requirements.txt`` or ``pyproject.toml`` is missing from the generated file.
"""
from __future__ import annotations

import hashlib
import importlib.metadata as md
import re
import sys
import tomllib
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent

# Packages that pip installs but that are not part of the application.
SKIP = {"pip", "setuptools", "wheel"}

# SPDX identifiers for packages whose metadata carries a licence text or only a
# classifier instead of a licence expression. Checked against the licence files
# of the installed versions.
SPDX_FALLBACK = {
    "blinker": "MIT",
    "contourpy": "BSD-3-Clause",
    "cycler": "BSD-3-Clause",
    "itsdangerous": "BSD-3-Clause",
    "jinja2": "BSD-3-Clause",
    "kiwisolver": "BSD-3-Clause",
    "matplotlib": "PSF-2.0-based (Matplotlib licence)",
    "pywebview": "BSD-3-Clause",
    "qrcode": "BSD-3-Clause",
    "reportlab": "BSD-3-Clause",
}

# Spellings of the same licence found in package metadata, mapped to SPDX.
NORMALISE = {
    "MIT License": "MIT",
    "MIT license": "MIT",
    "License :: OSI Approved :: MIT License": "MIT",
    "Apache 2.0": "Apache-2.0",
    "Python Software Foundation License": "PSF-2.0",
    "PSFL": "PSF-2.0",
    "3-Clause BSD License": "BSD-3-Clause",
    "BSD License": "BSD-3-Clause",
}

KOPF = """# Third-party notices

Shelly Energy Analyzer is built on the work of others. This file lists the
third-party components that are part of the application and of its container
image, with their licences. The application's own licence is in
[LICENSE](LICENSE); it does not limit the rights these licences grant for their
components.

The list is generated by `scripts/drittlizenzen.py` from `requirements.txt`,
`pyproject.toml` and the installed package metadata. Python dependencies are
installed by pip and are not modified.

## Bundled front-end library

**plotly.js** — charts in the web dashboard. It ships inside the `plotly`
Python package and is served unmodified as `/static/plotly.min.js`.
MIT License, Copyright 2012-2026 Plotly, Inc. The file carries its own licence
header; the components bundled into it are under the MIT and 3-Clause BSD
licences. The licence text of the `plotly` package is reproduced below.

## Container image

The container image (see `Dockerfile`) additionally contains:

- **Python** (official `python` base image) — Python Software Foundation
  License 2.0, <https://docs.python.org/3/license.html>
- **Debian packages** of the base image and the build tools installed with
  `apt-get` — each under its own licence, see `/usr/share/doc/<package>/copyright`
  inside the image
- **Tailscale {tailscale}** (`tailscaled`, `tailscale`) — BSD 3-Clause License,
  Copyright (c) Tailscale Inc & AUTHORS, <https://github.com/tailscale/tailscale>
  (downloaded at build time from the publisher, pinned to a fixed version)

The Watchtower container in `docker-compose.yml` is a separate, optional image
that is pulled from its publisher; it is not part of this application's image.

## Python packages

Every package pip installs for the application. Platform-specific packages that
pip installs only on other operating systems (for example the macOS and Windows
backends of pywebview) are not listed; regenerate the file on that platform to
include them. The licence texts follow below.

"""


def norm(name: str) -> str:
    return re.sub(r"[-_.]+", "-", name).lower()


def req_names() -> list[str]:
    out = []
    for line in (ROOT / "requirements.txt").read_text().splitlines():
        line = line.split("#", 1)[0].strip()
        if line:
            out.append(norm(re.split(r"[<>=!~;\[ ]", line, maxsplit=1)[0]))
    proj = tomllib.loads((ROOT / "pyproject.toml").read_text())["project"]
    specs = list(proj.get("dependencies", []))
    for extra in (proj.get("optional-dependencies") or {}).values():
        specs += extra
    for spec in specs:
        out.append(norm(re.split(r"[<>=!~;\[ ]", spec.strip(), maxsplit=1)[0]))
    return sorted(set(out))


def closure(roots: list[str]) -> dict[str, md.Distribution]:
    try:
        from packaging.requirements import Requirement
    except ImportError:  # pragma: no cover - packaging comes with pip's tree
        raise SystemExit("run this script in an environment with `packaging` installed")
    installed = {norm(d.metadata["Name"]): d for d in md.distributions()}
    seen: dict[str, md.Distribution] = {}
    todo = list(roots)
    while todo:
        n = todo.pop()
        if n in seen or n in SKIP:
            continue
        d = installed.get(n)
        if d is None:
            if n in roots:
                raise SystemExit(f"{n} is not installed: install requirements.txt first")
            continue  # extra or platform-specific dependency of another OS
        seen[n] = d
        for r in d.requires or []:
            req = Requirement(r)
            if req.marker is not None and not req.marker.evaluate({"extra": ""}):
                continue
            todo.append(norm(req.name))
    return seen


def licence_expression(d: md.Distribution) -> str:
    meta = d.metadata
    n = norm(meta["Name"])
    expr = (meta.get("License-Expression") or "").strip()
    if expr:
        return expr
    if n in SPDX_FALLBACK:
        return SPDX_FALLBACK[n]
    lic = (meta.get("License") or "").strip()
    if lic and len(lic) <= 60 and "\n" not in lic:
        return NORMALISE.get(lic, lic)
    classifiers = [c.split("::")[-1].strip() for c in meta.get_all("Classifier") or []
                   if c.startswith("License ::")]
    found = ", ".join(classifiers) or "see licence file"
    return NORMALISE.get(found, found)


def licence_files(d: md.Distribution) -> list[tuple[str, str]]:
    """Licence files of one installed package.

    Everything under ``<dist-info>/licenses/`` (it carries the licences of
    components bundled in the package, e.g. numpy and pandas) plus licence-named
    files directly in ``<dist-info>/``.
    """
    out = []
    for f in d.files or []:
        parts = f.parts
        if not parts[0].endswith(".dist-info") or len(parts) < 2:
            continue
        if parts[1] == "licenses":
            wanted = len(parts) > 2
        else:
            wanted = len(parts) == 2 and parts[-1].upper().startswith(
                ("LICENSE", "LICENCE", "COPYING", "NOTICE"))
        if not wanted:
            continue
        p = Path(d.locate_file(f))
        if p.is_file():
            label = "/".join(parts[2:] if parts[1] == "licenses" else parts[1:])
            out.append((label, p.read_text(encoding="utf-8", errors="replace").strip()))
    return sorted(out)


def tailscale_version() -> str:
    m = re.search(r"ARG TAILSCALE_VERSION=([\w.]+)", (ROOT / "Dockerfile").read_text())
    return m.group(1) if m else "(version pinned in Dockerfile)"


def _copyleft_note(names: list[str]) -> str:
    if not names:
        return ""
    return ("\n\n## Notes on copyleft licences\n\n"
            + ", ".join(names) + ": used as separately installed, unmodified "
            "libraries. The licences allow replacing them: install another version "
            "with pip and the application uses that one. The full licence texts "
            "follow below.")


def main() -> int:
    dists = closure(req_names())
    lines, texts, copyleft = [], {}, []
    for n in sorted(dists):
        d = dists[n]
        name = d.metadata["Name"]
        expr = licence_expression(d)
        if re.search(r"\b(L?GPL|MPL)", expr) and " OR " not in expr:
            copyleft.append(f"`{name}` ({expr})")
        url = (d.metadata.get("Home-page") or "").strip()
        if not url:
            for pu in d.metadata.get_all("Project-URL") or []:
                if pu.lower().startswith(("homepage", "source", "repository")):
                    url = pu.split(",", 1)[1].strip()
                    break
        lines.append(f"- `{name}` {d.version} — {expr}"
                     + (f" — <{url}>" if url else ""))
        for fname, text in licence_files(d):
            if not text:
                continue
            h = hashlib.sha256(text.encode()).hexdigest()
            texts.setdefault(h, (text, []))[1].append(f"{name} {d.version} ({fname})")
    out = [KOPF.replace("{tailscale}", tailscale_version()), "\n".join(lines),
           _copyleft_note(copyleft), "\n\n## Licence texts\n"]
    for text, who in sorted(texts.values(), key=lambda t: sorted(t[1])[0].lower()):
        out.append("\n---\n\nUsed by: " + ", ".join(sorted(set(who)))
                   + "\n\n```text\n" + text + "\n```\n")
    sys.stdout.write("".join(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
